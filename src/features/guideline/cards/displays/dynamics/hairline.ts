// 판을 맞붙이는 방식. Typography 토픽에서 정해져 다른 위젯으로 퍼졌다.
//
// 🔴 컨테이너와 셀은 **짝으로만** 성립한다. 컨테이너가 틈을 선 색으로 칠하고, 셀이 그 위를 불투명하게
//    덮어 틈만 남긴다. 그래서 선은 어디서나 정확히 1px이다.
// 🔴 셀마다 테두리를 두고 gap을 0으로 두는 방식은 쓰지 않는다 — 맞닿은 자리가 2px이 된다.
//    반대로 셀 테두리만 걷으면 선이 아예 사라진다. 선을 그리는 주체는 컨테이너 하나여야 한다.
// 🔴 셀 배경을 투명으로 두지 말 것 — 컨테이너의 선 색이 셀 전체에 비친다.
//
// 🔴 react·이미지 import 금지(schema가 참조하는 모듈과 같은 폴더다).

/** 맞붙임 컨테이너. `grid`/`flex`와 함께 쓴다. p-px가 바깥 테두리까지 같은 선으로 닫는다. */
export const HAIRLINE_GRID = 'gap-px bg-border p-px'

/** 맞붙임 셀. 틈을 가리기만 하면 되므로 배경만 준다(면 색이 아니라 페이지 배경이다). */
export const HAIRLINE_CELL = 'bg-background'
